-- ─────────────────────────────────────────────
-- 5) EXERCICES / ENTRAÎNEMENTS
--    Créés par les coachs, lisibles par tous les utilisateurs connectés.
-- ─────────────────────────────────────────────
create table if not exists public.trainings (
  id          text primary key,            -- ex. 'trn-<timestamp>'
  created_by  uuid not null references auth.users(id) on delete cascade,
  author_name text,
  type        text,                        -- exercice | entrainement
  title       text not null,
  category    text,
  level       text,
  duration    integer,
  objective   text,
  description text,
  created_at  timestamptz default now()
);

alter table public.trainings enable row level security;
create index if not exists trainings_author_idx on public.trainings(created_by);

-- Lecture : tout utilisateur connecté (les joueurs voient les exercices des coachs)
drop policy if exists "trainings_select_auth" on public.trainings;
create policy "trainings_select_auth" on public.trainings
  for select using (auth.role() = 'authenticated');

-- Écriture : uniquement l'auteur
drop policy if exists "trainings_write_own" on public.trainings;
create policy "trainings_write_own" on public.trainings
  for all using (auth.uid() = created_by) with check (auth.uid() = created_by);

-- ─────────────────────────────────────────────
-- 6) RÉALISATIONS D'EXERCICES (par joueur)
-- ─────────────────────────────────────────────
create table if not exists public.training_done (
  user_id     uuid not null references auth.users(id) on delete cascade,
  training_id text not null,
  count       integer default 0,
  last_done   timestamptz,
  primary key (user_id, training_id)
);

alter table public.training_done enable row level security;

drop policy if exists "training_done_all_own" on public.training_done;
create policy "training_done_all_own" on public.training_done
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

