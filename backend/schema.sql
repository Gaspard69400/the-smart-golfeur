-- ─────────────────────────────────────────────
-- 1) PROFILS (extension de auth.users)
-- ─────────────────────────────────────────────
create table if not exists public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  name       text,
  hcp        numeric,
  role       text default 'player',       -- player | captain | coach | head
  color      text,
  bg         text,
  initials   text,
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
  for insert with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
  for update using (auth.uid() = id);

-- Création automatique d'un profil à l'inscription
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, hcp, role, color, bg, initials)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    nullif(new.raw_user_meta_data->>'hcp', '')::numeric,
    coalesce(new.raw_user_meta_data->>'role', 'player'),
    coalesce(new.raw_user_meta_data->>'color', '#C9A84C'),
    coalesce(new.raw_user_meta_data->>'bg', 'rgba(201,168,76,0.2)'),
    coalesce(new.raw_user_meta_data->>'initials', upper(left(coalesce(new.raw_user_meta_data->>'name', new.email), 2)))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ─────────────────────────────────────────────
-- 2) PARTIES (rounds)
-- ─────────────────────────────────────────────
create table if not exists public.rounds (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  played_on   date,
  course      text,
  course_id   text,
  score       integer,
  par         integer,
  diff        numeric,
  fir         integer,
  fir_total   integer,
  gir         integer,
  putts       integer,
  cond        text,
  format      text,
  hcp         numeric,
  notes       text,
  scores      jsonb,
  sg_tee      numeric,
  sg_app      numeric,
  sg_arg      numeric,
  sg_putt     numeric,
  created_at  timestamptz default now()
);

alter table public.rounds enable row level security;
create index if not exists rounds_user_idx on public.rounds(user_id);

drop policy if exists "rounds_all_own" on public.rounds;
create policy "rounds_all_own" on public.rounds
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

