-- THE SMART GOLFER — Amis et profils (S68)
-- À coller EN ENTIER dans : Supabase → SQL Editor → New query → Run
-- Idempotent (on peut le relancer sans risque).
--
-- Ce que ça ajoute :
--  1. Une table `friendships` : une demande (pending) devient une amitié
--     (accepted) quand l'autre accepte. Personne n'écrit dedans directement :
--     tout passe par les fonctions ci-dessous, qui vérifient qui a le droit.
--  2. Un « code ami » par joueur (profiles.friend_code) → lien …/?ami=CODE.
--     Ouvrir le lien (ou saisir le code) rend amis tout de suite ; chercher
--     quelqu'un par son nom envoie une demande qu'il doit accepter.
--  3. Des amis se voient comme des membres d'un même groupe : profil, parties,
--     fil d'activité, 👏 et commentaires.
--  4. La fiche joueur (player_card) devient un vrai profil : visible en entier
--     si le profil est public, si vous êtes amis ou dans un même groupe ;
--     sinon seulement le nom, pour pouvoir l'ajouter en ami.
--  5. Recherche par nom : seulement les profils publics et les membres de tes
--     groupes (un profil privé se trouve par son code ou son lien d'ami).
-- ════════════════════════════════════════════

-- 1) Code ami
alter table public.profiles add column if not exists friend_code text;
create unique index if not exists profiles_friend_code_idx on public.profiles(friend_code) where friend_code is not null;

-- 2) Amitiés (une seule ligne par paire de joueurs, quel que soit le sens)
create table if not exists public.friendships (
  id           bigint generated by default as identity primary key,
  requester    uuid not null references auth.users(id) on delete cascade,
  addressee    uuid not null references auth.users(id) on delete cascade,
  status       text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at   timestamptz not null default now(),
  accepted_at  timestamptz,
  check (requester <> addressee)
);
create unique index if not exists friendships_pair_idx
  on public.friendships (least(requester, addressee), greatest(requester, addressee));
create index if not exists friendships_addressee_idx on public.friendships(addressee);
alter table public.friendships enable row level security;

drop policy if exists "friendships_select_own" on public.friendships;
create policy "friendships_select_own" on public.friendships
  for select using (auth.uid() = requester or auth.uid() = addressee);

-- 3) Qui est ami avec qui ?
create or replace function public.are_friends(other uuid)
returns boolean language sql security definer stable set search_path = public as $$
  select exists (
    select 1 from public.friendships f
    where f.status = 'accepted'
      and ((f.requester = auth.uid() and f.addressee = other)
        or (f.addressee = auth.uid() and f.requester = other))
  );
$$;

-- 'self' | 'friends' | 'pending_out' (j'ai demandé) | 'pending_in' (il m'a demandé) | 'none'
create or replace function public.friend_status(other uuid)
returns text language sql security definer stable set search_path = public as $$
  select case
    when other = auth.uid() then 'self'
    else coalesce((
      select case when f.status = 'accepted' then 'friends'
                  when f.requester = auth.uid() then 'pending_out'
                  else 'pending_in' end
      from public.friendships f
      where least(f.requester, f.addressee) = least(auth.uid(), other)
        and greatest(f.requester, f.addressee) = greatest(auth.uid(), other)
      limit 1), 'none')
  end;
$$;

-- 4) Des amis se voient comme des membres d'un même groupe
drop policy if exists "profiles_select_friend" on public.profiles;
create policy "profiles_select_friend" on public.profiles
  for select using (public.are_friends(id));

drop policy if exists "rounds_select_friend" on public.rounds;
create policy "rounds_select_friend" on public.rounds
  for select using (public.are_friends(user_id));

-- 👏 et commentaires : visibles aussi par les amis de l'auteur de la partie
create or replace function public.can_see_round(rid bigint)
returns boolean language sql security definer stable set search_path = public as $$
  select exists (
    select 1 from public.rounds r
    where r.id = rid and (r.user_id = auth.uid() or public.shares_group_with(r.user_id) or public.are_friends(r.user_id))
  );
$$;

-- 5) Mon code ami (créé à la première demande)
create or replace function public.ensure_friend_code()
returns text language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_code text;
begin
  if v_uid is null then return null; end if;
  select friend_code into v_code from public.profiles where id = v_uid;
  if v_code is not null then return v_code; end if;
  loop
    v_code := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    begin
      update public.profiles set friend_code = v_code where id = v_uid;
      exit;
    exception when unique_violation then
      -- code déjà pris : on retente
    end;
  end loop;
  return v_code;
end; $$;

-- 6) Retrouver un joueur par son code ami (nom et couleurs seulement)
create or replace function public.friend_lookup(p_code text)
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare p record;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false); end if;
  select id, name, initials, color, bg into p from public.profiles
   where friend_code = upper(trim(coalesce(p_code, '')));
  if p.id is null then return jsonb_build_object('ok', false); end if;
  return jsonb_build_object('ok', true, 'id', p.id, 'name', p.name, 'initials', p.initials,
                            'color', p.color, 'bg', p.bg, 'status', public.friend_status(p.id));
end; $$;

-- 6b) Ajouter par code ou par lien d'ami : amis TOUT DE SUITE.
--     Le code ne circule que si son propriétaire l'a donné (comme le code d'un groupe) :
--     le partager, c'est donner son accord d'avance. La recherche par nom, elle,
--     envoie une demande que l'autre doit accepter.
create or replace function public.add_friend_by_code(p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_other uuid; v_name text; f record;
begin
  if v_uid is null then return jsonb_build_object('ok', false, 'error', 'Non connecté'); end if;
  select id, name into v_other, v_name from public.profiles where friend_code = upper(trim(coalesce(p_code, '')));
  if v_other is null then return jsonb_build_object('ok', false, 'error', 'Code inconnu'); end if;
  if v_other = v_uid then return jsonb_build_object('ok', false, 'error', 'C''est ton propre code'); end if;
  select * into f from public.friendships
   where least(requester, addressee) = least(v_uid, v_other)
     and greatest(requester, addressee) = greatest(v_uid, v_other);
  if f.id is null then
    begin
      insert into public.friendships (requester, addressee, status, accepted_at)
      values (v_uid, v_other, 'accepted', now());
    exception when unique_violation then
      update public.friendships set status = 'accepted', accepted_at = coalesce(accepted_at, now())
       where least(requester, addressee) = least(v_uid, v_other)
         and greatest(requester, addressee) = greatest(v_uid, v_other);
    end;
  elsif f.status <> 'accepted' then
    update public.friendships set status = 'accepted', accepted_at = now() where id = f.id;
  end if;
  return jsonb_build_object('ok', true, 'status', 'friends', 'id', v_other, 'name', v_name);
end; $$;

-- 7) Demander en ami (si l'autre m'avait déjà demandé : c'est accepté tout de suite)
create or replace function public.send_friend_request(p_user uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); f record; v_pending int;
begin
  if v_uid is null then return jsonb_build_object('ok', false, 'error', 'Non connecté'); end if;
  if p_user is null or p_user = v_uid then return jsonb_build_object('ok', false, 'error', 'Impossible'); end if;
  if not exists (select 1 from public.profiles where id = p_user) then
    return jsonb_build_object('ok', false, 'error', 'Joueur introuvable');
  end if;
  select * into f from public.friendships
   where least(requester, addressee) = least(v_uid, p_user)
     and greatest(requester, addressee) = greatest(v_uid, p_user);
  if f.id is not null then
    if f.status = 'accepted' then return jsonb_build_object('ok', true, 'status', 'friends'); end if;
    if f.requester = v_uid then return jsonb_build_object('ok', true, 'status', 'pending_out'); end if;
    update public.friendships set status = 'accepted', accepted_at = now() where id = f.id;
    return jsonb_build_object('ok', true, 'status', 'friends');
  end if;
  select count(*) into v_pending from public.friendships where requester = v_uid and status = 'pending';
  if v_pending >= 50 then
    return jsonb_build_object('ok', false, 'error', 'Trop de demandes en attente');
  end if;
  begin
    insert into public.friendships (requester, addressee) values (v_uid, p_user);
  exception when unique_violation then
    return jsonb_build_object('ok', true, 'status', 'pending_out');
  end;
  return jsonb_build_object('ok', true, 'status', 'pending_out');
end; $$;

-- 8) Accepter ou refuser une demande reçue
create or replace function public.respond_friend_request(p_user uuid, p_accept boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_done int;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false); end if;
  if p_accept then
    update public.friendships set status = 'accepted', accepted_at = now()
     where requester = p_user and addressee = auth.uid() and status = 'pending';
  else
    delete from public.friendships
     where requester = p_user and addressee = auth.uid() and status = 'pending';
  end if;
  get diagnostics v_done = row_count;
  return jsonb_build_object('ok', v_done > 0, 'status', case when p_accept and v_done > 0 then 'friends' else 'none' end);
end; $$;

-- 9) Retirer un ami (ou annuler une demande envoyée)
create or replace function public.remove_friend(p_user uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_done int;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false); end if;
  delete from public.friendships
   where least(requester, addressee) = least(auth.uid(), p_user)
     and greatest(requester, addressee) = greatest(auth.uid(), p_user);
  get diagnostics v_done = row_count;
  return jsonb_build_object('ok', v_done > 0);
end; $$;

-- 10) Ma liste : amis, demandes reçues, demandes envoyées
create or replace function public.my_friends()
returns table (user_id uuid, name text, initials text, color text, bg text, hcp numeric,
               status text, since timestamptz, rounds_count int, last_played date)
language sql security definer stable set search_path = public as $$
  select o.id, p.name, p.initials, p.color, p.bg,
         case when f.status = 'accepted' then p.hcp end,
         case when f.status = 'accepted' then 'friends'
              when f.requester = auth.uid() then 'pending_out' else 'pending_in' end,
         coalesce(f.accepted_at, f.created_at),
         case when f.status = 'accepted' then (select count(*)::int from public.rounds r where r.user_id = o.id) end,
         case when f.status = 'accepted' then (select max(r.played_on) from public.rounds r where r.user_id = o.id) end
  from public.friendships f
  cross join lateral (select case when f.requester = auth.uid() then f.addressee else f.requester end as id) o
  join public.profiles p on p.id = o.id
  where auth.uid() in (f.requester, f.addressee)
  order by p.name;
$$;

-- 11) Chercher un joueur par son nom (profils publics + membres de mes groupes)
create or replace function public.search_players(p_query text)
returns table (user_id uuid, name text, initials text, color text, bg text, status text)
language sql security definer stable set search_path = public as $$
  select p.id, p.name, p.initials, p.color, p.bg, public.friend_status(p.id)
  from public.profiles p
  where auth.uid() is not null
    and length(trim(coalesce(p_query, ''))) >= 2
    and p.id <> auth.uid()
    and p.name ilike '%' || replace(replace(replace(trim(p_query), '\', '\\'), '%', '\%'), '_', '\_') || '%'
    and (p.public_profile or public.shares_group_with(p.id) or public.friend_status(p.id) <> 'none')
  order by p.name
  limit 20;
$$;

-- 12) Le profil d'un joueur
create or replace function public.player_card(p_user uuid)
returns jsonb language plpgsql security definer stable set search_path = public as $$
declare p record; v_rounds jsonb; v_count int; v_best int; v_last date; v_avg numeric;
        v_status text; v_friends int; v_visible boolean;
begin
  select id, name, initials, color, bg, hcp, public_profile, created_at into p from public.profiles where id = p_user;
  if p.id is null then return jsonb_build_object('ok', false); end if;
  v_status := public.friend_status(p.id);
  select count(*) into v_friends from public.friendships where status = 'accepted' and p.id in (requester, addressee);
  v_visible := p.public_profile or v_status in ('self', 'friends') or public.shares_group_with(p.id);
  if not v_visible then
    -- Profil privé : juste de quoi le reconnaître et l'ajouter en ami
    return jsonb_build_object('ok', false, 'private', true, 'id', p.id, 'name', p.name, 'initials', p.initials,
      'color', p.color, 'bg', p.bg, 'friend_status', v_status, 'friends_count', v_friends);
  end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.played_on desc nulls last), '[]'::jsonb) into v_rounds
    from (select played_on, course, score, par, diff from public.rounds
          where user_id = p.id order by played_on desc nulls last limit 8) x;
  select count(*), max(played_on) into v_count, v_last from public.rounds where user_id = p.id;
  select min(score) into v_best from public.rounds where user_id = p.id and public.is_full_round(scores, extra);
  select round(avg(score), 1) into v_avg from (
    select score from public.rounds where user_id = p.id and public.is_full_round(scores, extra)
    order by played_on desc nulls last limit 10) t;
  return jsonb_build_object('ok', true, 'id', p.id, 'name', p.name, 'initials', p.initials, 'color', p.color, 'bg', p.bg,
    'hcp', p.hcp, 'rounds_count', v_count, 'best18', v_best, 'avg18', v_avg, 'last_played', v_last, 'rounds', v_rounds,
    'friend_status', v_status, 'friends_count', v_friends, 'member_since', p.created_at, 'public', p.public_profile);
end; $$;

